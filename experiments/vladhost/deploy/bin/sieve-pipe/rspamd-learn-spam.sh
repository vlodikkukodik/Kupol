#!/bin/sh
# Обучение rspamd (спам): dovecot передаёт письмо на stdin, когда пользователь переносит его в «Спам» или обратно
# (см. deploy/mail/sieve/learn-spam.sieve). Единственный аргумент — имя ящика, только для журнала.
# Контроллер rspamd слушает 127.0.0.1:11334 и пускает только с самого сервера. Сбой обучения не должен ломать перенос письма,
# поэтому скрипт всегда завершается успехом, а причина попадает в системный журнал.
user=$(printf '%s' "${1:-unknown}" | tr -cd 'A-Za-z0-9@._+-')
if out=$(rspamc -h 127.0.0.1:11334 -t 15 learn_spam 2>&1); then
    logger -t vladhost-mail "rspamd: обучение (спам) для $user выполнено"
else
    logger -t vladhost-mail "rspamd: обучение (спам) для $user не удалось: $(printf '%s' "$out" | head -c 200 | tr '\n' ' ')"
fi
exit 0
